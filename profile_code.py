_SHARED = {"skills": True, "agents": True, "commands": True, "CLAUDE.md": False}
_MEMORY_IMPORT = b"<!-- Multi Claude shared instructions -->\n@~/.claude/CLAUDE.md\n"
# Shared by Python and PowerShell. Keep ordinary preferences and organization security controls.
_AUTH_ENV = re.compile(
    r"^(?:ANTHROPIC_(?:API_KEY|AUTH_TOKEN|BASE_URL|CUSTOM_HEADERS|PROFILE|CONFIG_DIR|ORGANIZATION_ID|"
    r"(?:AWS|BEDROCK|FOUNDRY|VERTEX|GOOGLE_CLOUD|FEDERATION|IDENTITY)_.*)|"
    r"CLAUDE_CODE_(?:OAUTH_.*|API_KEY_FILE_DESCRIPTOR|MESSAGING_TOKEN|"
    r"USE_(?:ANTHROPIC_AWS|ANTHROPIC_GOOGLE_CLOUD|BEDROCK|FOUNDRY|MANTLE|VERTEX))|"
    r"CLAUDE_CONFIG_DIR|CLAUDECODE)$", re.IGNORECASE
)


def _local(path):
    path = Path(path)
    if (not path.is_absolute() or not re.fullmatch("[A-Za-z]:", path.drive)
            or ".." in path.parts or any(ord(c) < 32 for c in str(path))):
        raise ValueError("A local absolute Windows path is required.")
    if any(os.path.isreserved(part) for part in path.parts[1:]):
        raise ValueError("Reserved Windows path.")
    return path


def _ordinary(path, directory=None):
    """Check each ancestor before accessing children. Missing final components may be created."""
    path = _local(path)
    for item in (*reversed(path.parents), path):
        try:
            entry = item.lstat()
        except FileNotFoundError:
            return False
        if stat.S_ISLNK(entry.st_mode) or entry.st_file_attributes & stat.FILE_ATTRIBUTE_REPARSE_POINT:
            raise OSError(f"Redirected profile path: {item}")
        if item != path or directory is True:
            if not stat.S_ISDIR(entry.st_mode):
                raise NotADirectoryError(str(item))
        elif directory is False and (not stat.S_ISREG(entry.st_mode) or entry.st_nlink != 1):
            raise OSError(f"Shared or invalid profile file: {item}")
    return True


def code_config_dir(base, profile_id):
    """Stable path for a UUID generated by the manager and persisted in its profile catalog."""
    if not isinstance(profile_id, str) or not re.fullmatch("[0-9a-f]{32}", profile_id):
        raise ValueError("A persistent profile UUID is required.")
    return _local(base) / "claude-code" / profile_id


def _prepare(base, profile_id):
    config = code_config_dir(base, profile_id)
    for folder in (config.parent, config, config / "anthropic"):
        if not _ordinary(folder, True):
            folder.mkdir(mode=0o700, exist_ok=True)
        _ordinary(folder, True)
    # These files, when present, belong to the official CLI. Never open or copy their contents.
    for filename in (".credentials.json", ".claude.json", "settings.json"):
        _ordinary(config / filename, False)
    _ordinary(config / "anthropic" / "active_config", False)
    _ordinary(config / "anthropic" / "configs", True)
    return config


def desktop_environment(base, profile_id):
    """Construct an isolated child environment without changing any parent or user settings."""
    config = _prepare(base, profile_id)
    env = {k: v for k, v in os.environ.items() if not _AUTH_ENV.fullmatch(k)}
    env["CLAUDE_CONFIG_DIR"] = str(config)
    env["ANTHROPIC_CONFIG_DIR"] = str(config / "anthropic")
    return env


def _powershell():
    return _local(os.environ["SYSTEMROOT"]) / "System32" / "WindowsPowerShell" / "v1.0" / "powershell.exe"


@functools.lru_cache(maxsize=16)
def _verify_signature(path, file_id, size, modified):
    # File identity and timestamps in the cache key invalidate the result after a CLI update.
    script = (
        "$p=$env:MULTI_CLAUDE_SIGNATURE_PATH; "
        "$s=Microsoft.PowerShell.Security\\Get-AuthenticodeSignature -LiteralPath $p; "
        "if ($s.Status -ne 'Valid') { exit 1 }; "
        "$publisher=$s.SignerCertificate.GetNameInfo('SimpleName',$false); "
        "if ($publisher -ne 'Anthropic, PBC') { exit 1 }; "
        "$v=[Diagnostics.FileVersionInfo]::GetVersionInfo($p); "
        "if ($v.ProductName -in 'Claude','Claude Desktop' -or $v.FileDescription -eq 'Claude Desktop') { exit 1 }; "
        "exit 0"
    )
    shell = _powershell()
    # Windows PowerShell must load its own security module even when started from PowerShell 7.
    env = dict(os.environ, MULTI_CLAUDE_SIGNATURE_PATH=str(path), PSMODULEPATH=str(shell.parent / "Modules"))
    try:
        result = subprocess.run([str(shell), "-NoLogo", "-NoProfile", "-NonInteractive", "-Command", script],
                                env=env, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                                stderr=subprocess.DEVNULL, timeout=12, creationflags=subprocess.CREATE_NO_WINDOW)
    except (OSError, subprocess.TimeoutExpired):
        return False
    return result.returncode == 0


def _signed_by_anthropic(path):
    info = path.stat()
    return _verify_signature(path, (info.st_dev, info.st_ino), info.st_size, info.st_mtime_ns)


def find_claude_code():
    """Discover official native, WinGet and current global npm installations, without invoking a candidate."""
    candidates = []
    user = os.environ.get("USERPROFILE")
    if user:
        native = Path(user) / ".local"
        candidates.append((native / "bin" / "claude.exe", native))
    for root, subdir in (("LOCALAPPDATA", "Microsoft/WinGet"), ("ProgramFiles", "WinGet")):
        if os.environ.get(root):
            winget = Path(os.environ[root]) / subdir / "Packages"
            if winget.is_absolute() and re.fullmatch("[A-Za-z]:", winget.drive):
                for package in winget.glob("Anthropic.ClaudeCode_*"):
                    candidates.append((package / "claude.exe", package))
    prefixes = [Path(p.strip('"')) for p in os.environ.get("PATH", "").split(os.pathsep) if p]
    if os.environ.get("APPDATA"):
        prefixes.insert(0, Path(os.environ["APPDATA"]) / "npm")
    for prefix in prefixes:
        package = prefix / "node_modules" / "@anthropic-ai"
        candidates.append((package / "claude-code" / "bin" / "claude.exe", package))
        arch = "arm64" if platform.machine().lower() in ("arm64", "aarch64") else "x64"
        native_package = f"claude-code-win32-{arch}"
        for scope in (package, package / "claude-code" / "node_modules" / "@anthropic-ai"):
            candidates.append((scope / native_package / "claude.exe", scope / native_package))
    for candidate, root in dict.fromkeys(candidates):
        if not candidate.is_absolute() or not re.fullmatch("[A-Za-z]:", candidate.drive):
            continue
        try:
            resolved = candidate.resolve(strict=True)
            if resolved.is_relative_to(root) and resolved.is_file() and _signed_by_anthropic(resolved):
                return candidate
        except (OSError, RuntimeError):
            continue
    return None


def _launch_spec(base, profile_id, login):
    if profile_id is None and login:
        raise ValueError("Choose an isolated profile to sign in.")
    cli = find_claude_code()
    if cli is None:
        raise FileNotFoundError("Install the native Windows Claude Code CLI: https://code.claude.com/docs/en/setup")
    env = None if profile_id is None else desktop_environment(base, profile_id)
    args = [str(cli)]
    if login:
        args += ["auth", "login"]
    return args, env


def open_terminal(base, profile_id, *, login=False):
    """Start the interactive CLI in its own visible console. The shared mode inherits normal settings."""
    args, env = _launch_spec(base, profile_id, login)
    subprocess.Popen(args, env=env, cwd=os.environ["USERPROFILE"], creationflags=subprocess.CREATE_NEW_CONSOLE)


def _ps_literal(value):
    # PowerShell treats Unicode smart quotes as delimiters too. Express these characters as data.
    parts = re.split("(['‘’‚‛])", str(value))
    if len(parts) == 1:
        return "'" + parts[0] + "'"
    pieces = [f"[char]{ord(s)}" if i % 2 else "'" + s + "'" for i, s in enumerate(parts)]
    return "(" + "+".join(pieces) + ")"


def powershell_command(base, profile_id, *, login=False):
    """Call this manager to recheck the catalog, select the CLI and isolate the child at execution time."""
    if profile_id is None and login:
        raise ValueError("Choose an isolated profile to sign in.")
    if profile_id is not None:
        code_config_dir(base, profile_id)
    frozen = getattr(sys, "frozen", False)
    source = Path(__file__).with_name("Multi Claude.pyw")
    program = Path(sys.executable)
    default_base = program.parent if frozen else source.parent
    args = ["--code-terminal", profile_id or "shared"]
    if _local(base) != default_base:
        args += ["--manager-home", str(base)]
    if login:
        args.append("--login")
    if frozen:
        # PowerShell doesn't wait for a Windows GUI executable invoked interactively with &.
        arguments = _ps_literal(subprocess.list2cmdline(args))
        return (f"$LASTEXITCODE=(Start-Process -Wait -PassThru -NoNewWindow -FilePath {_ps_literal(program)} "
                f"-WorkingDirectory $PWD -ArgumentList ({arguments}+' --console-pid '+$PID)).ExitCode")
    if program.name.lower() == "pythonw.exe":
        program = program.with_name("python.exe")
    return "& " + " ".join(_ps_literal(v) for v in [program, source, *args])


def run_terminal_command(default_base, arguments):
    """Handle --code-terminal without opening Tk or changing the caller's working directory."""
    if not arguments:
        raise ValueError("Choose a profile UUID or shared.")
    profile_id = None if arguments[0] == "shared" else arguments[0]
    args = list(arguments[1:])
    base = _local(default_base)
    if args[:1] == ["--manager-home"] and len(args) >= 2:
        base = _local(args[1])
        del args[:2]
    console_pid = -1
    if len(args) >= 2 and args[-2] == "--console-pid":
        if not re.fullmatch(r"[1-9][0-9]{0,9}", args[-1]) or int(args[-1]) >= 2**32:
            raise ValueError("Invalid console process ID.")
        console_pid = int(args[-1])
        del args[-2:]
    if args not in ([], ["--login"]):
        raise ValueError("Invalid terminal arguments.")
    if profile_id is not None:
        code_config_dir(base, profile_id)
        catalog = base / "perfis.db"
        if not _ordinary(catalog, False):
            raise FileNotFoundError(str(catalog))
        try:
            with contextlib.closing(sqlite3.connect(catalog.as_uri() + "?mode=ro", uri=True)) as db:
                require_claude_catalog(db, profile_id)
                found = db.execute("SELECT o.sharing FROM profile_options AS o JOIN perfis AS p ON p.id = o.profile "
                                   "WHERE o.code_key = ? AND o.isolated = 1", (profile_id,)).fetchone()
                if found and db.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='config'").fetchone():
                    pinned = db.execute("SELECT valor FROM config WHERE chave=?", ("wpf_code_home_" + profile_id,)).fetchone()
                    if pinned:
                        if not isinstance(pinned[0], str):
                            raise ValueError("Invalid Claude Code home in the profile catalog.")
                        base = _local(pinned[0])
        except sqlite3.Error as exc:
            raise OSError(f"Cannot read profile catalog: {catalog}") from exc
        if found is None:
            raise ValueError("This isolated Claude Code profile is no longer available.")
        if found[0]:
            share_resources(base, profile_id, True, refresh=True)
    argv, env = _launch_spec(base, profile_id, args == ["--login"])
    if getattr(sys, "frozen", False):
        # The one-file bootloader and its Python child are both windowed. Use the actual calling shell's PID.
        kernel = ctypes.WinDLL("kernel32", use_last_error=True)
        if not kernel.AttachConsole(ctypes.c_uint32(console_pid)) and ctypes.get_last_error() != 5:
            raise OSError("Open this command in a PowerShell console.")
        with open("CONIN$", "rb", buffering=0) as con_in, open("CONOUT$", "wb", buffering=0) as con_out:
            return subprocess.run(argv, env=env, stdin=con_in, stdout=con_out, stderr=con_out).returncode
    return subprocess.run(argv, env=env).returncode


def _link_identity(path, source):
    try:
        info = path.lstat()
        if path.name == "CLAUDE.md":
            if (stat.S_ISREG(info.st_mode) and info.st_nlink == 1
                    and not info.st_file_attributes & stat.FILE_ATTRIBUTE_REPARSE_POINT
                    and info.st_size == len(_MEMORY_IMPORT) and path.read_bytes() == _MEMORY_IMPORT):
                return [info.st_dev, info.st_ino]
        elif info.st_reparse_tag == stat.IO_REPARSE_TAG_MOUNT_POINT:
            target = str(path.readlink()).removeprefix("\\\\?\\")
            if Path(target) == source:
                return [info.st_dev, info.st_ino]
    except FileNotFoundError:
        pass
    return None


def _write_sharing(manifest, owned):
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=manifest.parent, delete=False) as tmp:
        temp_path = Path(tmp.name)
    try:
        temp_path.write_text(json.dumps(owned), encoding="utf-8")
        temp_path.replace(manifest)
    finally:
        temp_path.unlink(missing_ok=True)


def share_resources(base, profile_id, enabled, *, refresh=False):
    """Link missing resources only. Undo only links created by this manager and still identical."""
    config = _prepare(base, profile_id)
    guard = config / ".multi-claude-sharing.lock"
    _ordinary(guard, False)
    with os.fdopen(os.open(guard, os.O_RDWR | os.O_CREAT | os.O_BINARY, 0o600), "r+b") as lock:
        msvcrt.locking(lock.fileno(), msvcrt.LK_LOCK, 1)
        try:
            mode = lock.read(1)
            if refresh and mode == b"0":
                # A terminal may have read the catalog just before the editor disabled sharing.
                return ()
            result = _sync_sharing(config, enabled)
            desired = b"1" if enabled else b"0"
            if desired != mode:
                lock.seek(0)
                lock.write(desired)
                lock.flush()
            return result
        finally:
            lock.seek(0)
            msvcrt.locking(lock.fileno(), msvcrt.LK_UNLCK, 1)


def _sync_sharing(config, enabled):
    source = _local(os.environ["USERPROFILE"]) / ".claude"
    manifest = config / ".multi-claude-shared.json"
    owned = {}
    if _ordinary(manifest, False):
        owned = json.loads(manifest.read_text(encoding="utf-8"))
        if (not isinstance(owned, dict) or not set(owned) <= _SHARED.keys()
                or not all(isinstance(v, list) and len(v) == 2 and all(type(i) is int for i in v)
                           for v in owned.values())):
            raise ValueError(f"Invalid sharing record: {manifest}")
    previous = dict(owned)
    created = {}
    staged = {}
    backup = tempfile.TemporaryDirectory(dir=config) if owned and not enabled else None
    try:
        for name, directory in _SHARED.items():
            src, dst = source / name, config / name
            if name in owned and _link_identity(dst, src) != owned[name]:
                del owned[name]
            if enabled:
                if not os.path.lexists(dst) and _ordinary(src, directory):
                    if directory:
                        _winapi.CreateJunction(str(src), str(dst))
                    else:
                        with dst.open("xb") as memory:
                            memory.write(_MEMORY_IMPORT)
                    created[name] = owned[name] = _link_identity(dst, src)
            elif name in owned:
                saved = Path(backup.name) / name
                dst.rename(saved)
                staged[name] = saved
                del owned[name]
        if owned != previous:
            _write_sharing(manifest, owned)
    except (OSError, ValueError):
        for name, saved in staged.items():
            try:
                saved.rename(config / name)  # Windows refuses to replace anything created in the meantime.
            except OSError:
                if not os.path.lexists(config / name):
                    raise
        for name, identity in created.items():
            dst = config / name
            if identity and _link_identity(dst, source / name) == identity:
                if _SHARED[name]:
                    dst.rmdir()
                else:
                    dst.unlink()
        if staged:
            restored = {name: identity for name, identity in previous.items()
                        if _link_identity(config / name, source / name) == identity}
            if restored != previous:
                _write_sharing(manifest, restored)
        raise
    finally:
        if backup is not None:
            backup.cleanup()  # On Windows rmtree removes directory junctions without traversing them.
    return tuple(owned)
